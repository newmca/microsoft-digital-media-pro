#!/usr/bin/env python3
"""Regenerate src/dmpkeys/data/keycodes.json.

For every kernel KEY_* code: the level-1 keysym that the default XKB keymap
(rules=evdev, model=pc105, layout=us) produces for it, and the Qt::Key value
Qt 6 turns that keysym into.

Qt has no public keysym->Qt::Key API; its table (qxkbcommon.cpp, KeyTbl) is
compiled into libQt6Gui as sorted (uint32 keysym, uint32 qtkey) pairs, so this
reads it straight out of the library. F-keys are computed (Key_F1 + n - 1);
Qt does that arithmetically, not via the table.

Needs: libxkbcommon, libQt6Gui, linux/input-event-codes.h. Linux x86-64.
Usage: tools/gen_keycodes.py [path/to/libQt6Gui.so.6]
"""
import ctypes
import glob
import json
import re
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/dmpkeys/data/keycodes.json"
HEADER = "/usr/include/linux/input-event-codes.h"
QT_KEY_MIN, QT_KEY_MAX = 0x01000000, 0x0120FFFF
QT_KEY_F1 = 0x01000030

xkb = ctypes.CDLL("libxkbcommon.so.0")


class RuleNames(ctypes.Structure):
    _fields_ = [(n, ctypes.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]


xkb.xkb_context_new.restype = ctypes.c_void_p
xkb.xkb_keymap_new_from_names.restype = ctypes.c_void_p
xkb.xkb_keymap_new_from_names.argtypes = [ctypes.c_void_p, ctypes.POINTER(RuleNames), ctypes.c_int]
xkb.xkb_keymap_key_get_syms_by_level.argtypes = [
    ctypes.c_void_p, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32,
    ctypes.POINTER(ctypes.POINTER(ctypes.c_uint32))]
xkb.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]


def keysym_name(ks: int) -> str:
    buf = ctypes.create_string_buffer(64)
    xkb.xkb_keysym_get_name(ks, buf, 64)
    return buf.value.decode()


def kernel_keys() -> dict[str, int]:
    keys: dict[str, int] = {}
    text = Path(HEADER).read_text()
    for m in re.finditer(r"#define\s+KEY_(\w+)\s+(0x[0-9a-fA-F]+|\d+)", text):
        name, code = m.group(1).lower(), int(m.group(2), 0)
        if name not in ("max", "cnt", "min_interesting"):
            keys.setdefault(name, code)  # first definition wins over later aliases
    return keys


def keymap_keysyms(codes) -> dict[int, int]:
    ctx = xkb.xkb_context_new(0)
    names = RuleNames(b"evdev", b"pc105", b"us", b"", b"")
    keymap = xkb.xkb_keymap_new_from_names(ctx, ctypes.byref(names), 0)
    out = {}
    for code in codes:
        if code + 8 > 255:
            continue
        syms = ctypes.POINTER(ctypes.c_uint32)()
        if xkb.xkb_keymap_key_get_syms_by_level(keymap, code + 8, 0, 0, ctypes.byref(syms)) > 0:
            out[code] = syms[0]
    return out


def qt_key_for(lib: bytes, keysym: int) -> int | None:
    """Find the (keysym, qtkey) pair in Qt's table; None if absent or ambiguous."""
    pattern, hits, i = struct.pack("<I", keysym), set(), lib.find(struct.pack("<I", keysym))
    while i != -1:
        if i % 4 == 0:
            q = struct.unpack_from("<I", lib, i + 4)[0]
            if QT_KEY_MIN <= q <= QT_KEY_MAX:
                hits.add(q)
        i = lib.find(pattern, i + 1)
    return hits.pop() if len(hits) == 1 else None


def main() -> None:
    lib_path = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob("/usr/lib*/libQt6Gui.so.6*"))[0]
    lib = Path(lib_path).read_bytes()
    keys = kernel_keys()
    syms = keymap_keysyms(keys.values())
    table = {}
    for name, code in sorted(keys.items(), key=lambda kv: kv[1]):
        ks = syms.get(code)
        sym = keysym_name(ks) if ks else None
        qt = None
        if sym and re.fullmatch(r"F\d+", sym):
            qt = QT_KEY_F1 + int(sym[1:]) - 1
        elif ks and len(sym) > 1:  # single characters are ordinary keys; not needed
            qt = qt_key_for(lib, ks)
        table[name] = {"code": code, "keysym": sym, "qt": qt}
    OUT.write_text(json.dumps({
        "_comment": [
            "Kernel key name (input-event-codes.h, lowercase, no KEY_ prefix) -> evdev code,",
            "level-1 keysym in the default XKB keymap (xkeyboard-config rules=evdev model=pc105 layout=us,",
            "which includes inet(evdev)), and the Qt::Key that keysym becomes (Qt 6 qxkbcommon table).",
            "Generated by tools/gen_keycodes.py; keycodes > 247 have no keysym (X keycode = evdev + 8 <= 255).",
        ],
        "keys": table,
    }, indent=1, sort_keys=True) + "\n")
    print(f"wrote {len(table)} keys to {OUT}")


if __name__ == "__main__":
    main()
